import assert from 'node:assert/strict';
const hooks=new Map();let state;
const actor={id:'a',type:'aventuria.hero',isOwner:true,getFlag:()=>0,testUserPermission:user=>user.id==='gm'};
const actorB={...actor,id:'b'};
const gm={id:'gm',active:true,isGM:true};
const users=[gm,{id:'p1',active:true,character:actor},{id:'p2',active:false,character:actorB},{id:'p3',active:true,character:actor}];users.get=id=>users.find(u=>u.id===id);users.activeGM=gm;
let settingOptions;
globalThis.Hooks={once:(key,fn)=>hooks.set(key,fn),callAll(){}};
globalThis.foundry={utils:{deepClone:structuredClone,randomID:()=>String(Math.random())}};
globalThis.game={user:gm,users,actors:{get:id=>id==='a'?actor:actorB,filter:predicate=>[actor,actorB].filter(predicate)},i18n:{localize:k=>k},settings:{register:(m,k,opts)=>{settingOptions=opts;state=structuredClone(opts.default);},get:()=>state,set:async(m,k,value)=>{await new Promise(r=>setTimeout(r,2));state=value;}},socket:{on(){},emit(){}}};
const notices=[];globalThis.ui={notifications:{warn:msg=>notices.push(msg)}};
const {registerFatePool,setFatePool,startFatePool,changeFate,heroFate,returnAllFatePoints}=await import('../../scripts/actors/hero-fate.mjs');
registerFatePool();
assert.equal(settingOptions.scope,'world');
await startFatePool();assert.equal(state.pool,2,'Only connected assigned heroes count; duplicates and offline users excluded');
await setFatePool(1);
await Promise.all([changeFate(actor,{delta:1}),changeFate(actorB,{delta:1})]);
assert.equal(state.pool,0);assert.equal(heroFate(actor),1);assert.equal(heroFate(actorB),0);
assert.equal(notices.length,1,'Second concurrent claim rejected');
await setFatePool(5);await changeFate(actor,{value:3});assert.equal(state.pool,3);assert.equal(heroFate(actor),3);
await setFatePool(-1);assert.equal(state.pool,3);
console.log('Passed: world pool, unique hero start count, serialized last-point claims, direct allocation, invalid pool values.');

await changeFate(actor,{delta:-1});assert.equal(state.pool,4);assert.equal(heroFate(actor),2);
await changeFate(actor,{value:0});assert.equal(state.pool,6);assert.equal(heroFate(actor),0);
await changeFate(actor,{delta:-1});assert.equal(state.pool,6,'Zero cannot return an extra point');
assert.equal(state.pool+heroFate(actor)+heroFate(actorB),6,'Transfers preserve total');
console.log('Passed: minus/direct-entry return points, zero guard, total preserved.');

users.splice(1);gm.character=actor;
await startFatePool();assert.equal(state.pool,2,'A hero assigned only to the GM counts in solo play');
users.push({id:'duplicate',active:false,character:actor});
await startFatePool();assert.equal(state.pool,2,'Shared assignments count once');
users.push({id:'offline',active:false,character:actorB});
await startFatePool();assert.equal(state.pool,2,'Offline assigned heroes do not count at adventure start');
users.at(-1).active=true;
await startFatePool();assert.equal(state.pool,4,'Connecting another assigned hero increases the next start value');
users.push({id:'nohero',active:true},{id:'nonhero',active:true,character:{id:'other',type:'npc'}});
await startFatePool();assert.equal(state.pool,4,'Unassigned users and non-hero actors are excluded');
assert.equal(heroFate(actor),0,'Resetting pool leaves individual counters unchanged');
console.log('Passed: GM-only solo hero, duplicate assignment, offline hero, pool-only reset.');

await changeFate(actor,{delta:1});await changeFate(actorB,{delta:1});
const total=state.pool+heroFate(actor)+heroFate(actorB);
assert.equal(await returnAllFatePoints(),true);
assert.equal(state.pool,total);assert.equal(heroFate(actor),0);assert.equal(heroFate(actorB),0);
await returnAllFatePoints();assert.equal(state.pool,total,'Repeated cleanup cannot duplicate points');
actorB.getFlag=()=>3;delete state.heroes.b;
await returnAllFatePoints();assert.equal(state.pool,total+3);assert.equal(heroFate(actorB),0);
await returnAllFatePoints();assert.equal(state.pool,total+3,'Legacy flags cannot be refunded twice');
console.log('Passed: board-reset refund, all heroes, repeat reset, legacy fallback zero override.');
